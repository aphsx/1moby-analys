"use client";
/**
 * Monthly trend (DASHBOARD.md §7.1): is revenue growing, and is it more payers or more per payer?
 * One metric at a time (no dual axis); the tooltip and the table carry all three.
 */
import { useState } from "react";
import { Lightbulb } from "lucide-react";
import { Bar, BarChart, CartesianGrid, Cell, LabelList, ReferenceLine, ResponsiveContainer, Tooltip, XAxis, YAxis, type TooltipProps } from "recharts";
import { Delta, EmptyState, Panel, Provenance } from "@/components/ui";
import { formatBaht, formatBahtCompact, formatCount, formatMonth, formatPercent, formatSignedPercent } from "@/lib/format";
import { grew, type OverviewModel, type TrendMetric, type TrendSeries } from "./overview-model";

const METRICS: { key: TrendMetric; label: string; unit: string }[] = [
  { key: "rev", label: "รายได้", unit: "" },
  { key: "pay", label: "ผู้จ่ายเงิน", unit: "ราย" },
  { key: "mau", label: "ลูกค้าที่ส่งข้อความ", unit: "ราย" },
];

const fmt = (metric: TrendMetric, v: number) => (metric === "rev" ? formatBahtCompact(v) : formatCount(v));
const fmtTick = (metric: TrendMetric, v: number) => (metric === "rev" ? formatBahtCompact(v) : formatCount(v));
const label = (metric: TrendMetric) => METRICS.find((m) => m.key === metric)!.label;

function title(metric: TrendMetric, s: TrendSeries): string {
  const subject = { rev: "รายได้ครึ่งปีหลัง", pay: "ผู้จ่ายเงินต่อเดือน", mau: "ลูกค้าที่ส่งข้อความต่อเดือน" }[metric];
  if (s.growth == null) return `${label(metric)}รายเดือน`;
  if (Math.abs(s.growth) < 0.01) return `${subject}ทรงตัว`;
  return s.growth > 0 ? `${subject}${metric === "rev" ? "โตขึ้น" : "เพิ่มขึ้น"} ${formatPercent(s.growth)}` : `${subject}ลดลง ${formatPercent(-s.growth)}`;
}

/** Generated by rule from the data, never by an LLM (DASHBOARD.md §7.1). */
function note(metric: TrendMetric, m: OverviewModel): string | null {
  const { rev, pay, mau } = m.trend;
  if (metric === "rev") {
    const c = m.topContributor;
    if (c) {
      const since = c.firstMonth ? ` ที่เริ่มจ่ายเงิน ${formatMonth(c.firstMonth, true)}` : "";
      const ex = c.growthEx != null ? ` · ไม่นับบัญชีนี้ รายได้${grew(c.growthEx)}` : "";
      const per =
        c.arppuGrowthEx != null
          ? ` และยอดเฉลี่ยต่อผู้จ่ายเงิน${c.arppuGrowthEx >= 0 ? "เพิ่มขึ้น" : "ลดลง"} ${formatPercent(Math.abs(c.arppuGrowthEx))}`
          : "";
      return `รายได้ที่เพิ่มขึ้น ${formatPercent(c.share)} มาจากบัญชี #${c.accId}${since}${ex}${per}`;
    }
    if (rev.growth == null) return null;
    const peak = `${rev.months[rev.maxIndex].label} ทำรายได้สูงสุดของปีที่ ${formatBahtCompact(rev.months[rev.maxIndex].value)}`;
    if (!m.arppu || pay.growth == null) return `รายได้${grew(rev.growth)} เทียบครึ่งปีแรก · ${peak}`;
    const faster = rev.growth > pay.growth && m.arppu.growth > 0 ? "รายได้โตเร็วกว่าจำนวนคน: " : "";
    return `${faster}ผู้จ่ายเงินต่อเดือน${grew(pay.growth)} ส่วนยอดเฉลี่ยต่อผู้จ่ายเงินเปลี่ยนจาก ${formatBahtCompact(m.arppu.h1)} เป็น ${formatBahtCompact(m.arppu.h2)} (${formatSignedPercent(m.arppu.growth, 0)}) และ${peak}`;
  }
  if (metric === "pay") {
    if (pay.h1 == null || pay.h2 == null || pay.growth == null || rev.growth == null) return null;
    const rest = rev.growth > pay.growth ? "ส่วนที่เหลือมาจากยอดจ่ายต่อคนที่สูงขึ้น" : "ส่วนที่เหลือมาจากยอดจ่ายต่อคนที่ลดลง";
    return `ผู้จ่ายเงินเปลี่ยนจากเฉลี่ย ${formatCount(Math.round(pay.h1))} เป็น ${formatCount(Math.round(pay.h2))} รายต่อเดือน (${formatSignedPercent(pay.growth, 0)}) ${pay.growth < rev.growth ? "น้อยกว่า" : "มากกว่า"}รายได้ที่${grew(rev.growth)} ${rest}`;
  }
  if (mau.h1 == null || mau.h2 == null || mau.growth == null) return null;
  return `ลูกค้าที่ส่งข้อความต่อเดือน${grew(mau.growth)} (${formatCount(Math.round(mau.h1))} → ${formatCount(Math.round(mau.h2))} ราย)`;
}

export function MonthlyTrend({ model }: { model: OverviewModel }) {
  const [metric, setMetric] = useState<TrendMetric>("rev");
  const [view, setView] = useState<"chart" | "table">("chart");
  const [hover, setHover] = useState<number | null>(null);
  const s = model.trend[metric];
  const rows = s.months.map((mo, i) => ({
    label: mo.label,
    value: mo.value,
    rev: model.trend.rev.months[i].value,
    pay: model.trend.pay.months[i].value,
    mau: model.trend.mau.months[i].value,
    month: mo.month,
  }));
  const first = s.months[0];
  const last = s.months.at(-1);
  const period = /^\d+$/.test(model.yearLabel) && first && last ? `${first.label}–${last.label} ${model.yearLabel}` : model.yearLabel;
  const empty = model.trend.rev.months.every((m) => m.value === 0);
  const text = note(metric, model);

  return (
    <Panel
      title={title(metric, s)}
      info="ผู้จ่ายเงิน = บัญชีที่ชำระเงินมากกว่า ฿0 ในเดือนนั้น · ลูกค้าที่ส่งข้อความ = บัญชีที่ส่ง SMS หรือ Email ในเดือนนั้น · เส้นประ = ค่าเฉลี่ยต่อเดือนของแต่ละครึ่งปี ทั้ง 3 ตัวชี้วัดใช้แกนเวลาเดียวกัน สลับดูทีละตัว"
      meta={`${period} · ชี้แต่ละเดือนเพื่อดูตัวเลขทั้ง 3 ตัว`}
      right={<Provenance kind="fact" />}
    >
      {empty ? (
        <EmptyState title="ยังไม่มีการชำระเงินในช่วงนี้" />
      ) : (
        <>
          <div className="mb-3 flex flex-wrap items-center justify-between gap-2">
            <div className="flex rounded-control bg-raised p-1" role="group" aria-label="ตัวชี้วัด">
              {METRICS.map((m) => (
                <button
                  key={m.key}
                  type="button"
                  aria-pressed={metric === m.key}
                  onClick={() => {
                    setMetric(m.key);
                    setHover(null);
                  }}
                  className={`h-7 rounded-control px-3 text-small transition-colors duration-150 max-[859px]:h-9 ${
                    metric === m.key ? "bg-accent-soft font-semibold text-accent-ink" : "text-muted hover:text-text"
                  }`}
                >
                  {m.label}
                </button>
              ))}
            </div>
            <button type="button" onClick={() => setView(view === "chart" ? "table" : "chart")} className="text-small text-accent-ink underline-offset-2 hover:underline">
              {view === "chart" ? "ดูเป็นตาราง" : "ดูเป็นกราฟ"}
            </button>
          </div>

          {view === "chart" ? (
            <div
              role="img"
              aria-label={`${label(metric)}รายเดือน ${period}: ต่ำสุด ${fmt(metric, Math.min(...s.months.map((x) => x.value)))} สูงสุด ${fmt(metric, s.months[s.maxIndex].value)} ใน${s.months[s.maxIndex].label}`}
              className="h-[240px]"
            >
              <ResponsiveContainer width="100%" height="100%">
                <BarChart
                  data={rows}
                  margin={{ top: 20, right: 8, bottom: 0, left: 0 }}
                  onMouseMove={(st) => setHover(typeof st?.activeTooltipIndex === "number" ? st.activeTooltipIndex : null)}
                  onMouseLeave={() => setHover(null)}
                >
                  <CartesianGrid vertical={false} stroke="var(--grid)" />
                  <XAxis
                    dataKey="label"
                    axisLine={false}
                    tickLine={false}
                    interval="preserveStartEnd"
                    minTickGap={4}
                    tick={({ x, y, payload, index }: { x: number; y: number; payload: { value: string }; index: number }) => (
                      <text x={x} y={y + 12} textAnchor="middle" fontSize={12} fill="var(--axis-ink)" fontWeight={index === hover ? 600 : 400}>
                        {payload.value}
                      </text>
                    )}
                  />
                  <YAxis
                    axisLine={false}
                    tickLine={false}
                    width={56}
                    domain={[0, s.ticks.at(-1) ?? 0]}
                    ticks={s.ticks}
                    tick={{ fontSize: 12, fill: "var(--axis-ink)" }}
                    tickFormatter={(v: number) => fmtTick(metric, v)}
                  />
                  <Tooltip content={<BareTooltip metric={metric} model={model} />} cursor={{ fill: "var(--raised)" }} isAnimationActive={false} />
                  <Bar dataKey="value" maxBarSize={24} radius={[4, 4, 0, 0]} isAnimationActive={false}>
                    {rows.map((_, i) => (
                      <Cell key={i} fill={i === hover ? "var(--accent-ink)" : "var(--chart-1)"} />
                    ))}
                    <LabelList
                      dataKey="value"
                      content={({ x, y, width, index, value }) =>
                        index === s.maxIndex ? (
                          <text x={Number(x) + Number(width) / 2} y={Number(y) - 6} textAnchor="middle" fontSize={12} fontWeight={600} fill="var(--text)">
                            {fmt(metric, Number(value))}
                          </text>
                        ) : null
                      }
                    />
                  </Bar>
                  {s.h1 != null ? (
                    <ReferenceLine segment={[{ x: rows[0].label, y: s.h1 }, { x: rows[5].label, y: s.h1 }]} stroke="var(--text)" strokeWidth={2} strokeDasharray="4 3" ifOverflow="extendDomain" />
                  ) : null}
                  {s.h2 != null ? (
                    <ReferenceLine segment={[{ x: rows[6].label, y: s.h2 }, { x: rows[11].label, y: s.h2 }]} stroke="var(--text)" strokeWidth={2} strokeDasharray="4 3" ifOverflow="extendDomain" />
                  ) : null}
                </BarChart>
              </ResponsiveContainer>
            </div>
          ) : (
            <div className="overflow-x-auto">
              <table className="data-table">
                <thead>
                  <tr>
                    <th>เดือน</th>
                    {METRICS.map((m) => (
                      <th key={m.key} className="num">{m.label}</th>
                    ))}
                  </tr>
                </thead>
                <tbody>
                  {rows.map((r) => (
                    <tr key={r.month}>
                      <td>{formatMonth(r.month, true)}</td>
                      {METRICS.map((m) => (
                        <td key={m.key} className={`num ${metric === m.key ? "font-semibold" : ""}`}>
                          {m.key === "rev" ? formatBaht(r.rev) : formatCount(r[m.key])}
                        </td>
                      ))}
                    </tr>
                  ))}
                </tbody>
              </table>
            </div>
          )}

          {s.h1 != null && s.h2 != null ? (
            <div className="mt-3 grid grid-cols-2 gap-4">
              {[
                ["ครึ่งปีแรก · เฉลี่ยต่อเดือน", s.h1, null],
                ["ครึ่งปีหลัง · เฉลี่ยต่อเดือน", s.h2, s.growth],
              ].map(([name, v, g]) => (
                <div key={String(name)} className="border-t border-rule pt-2">
                  <p className="text-small text-muted">{name}</p>
                  <p className="text-section font-semibold text-text">
                    {fmt(metric, Number(v))} {g != null ? <Delta value={Number(g)} base="" /> : null}
                  </p>
                </div>
              ))}
            </div>
          ) : null}

          {text ? (
            <p className="mt-4 flex gap-2 rounded-control bg-raised p-3 text-small text-text">
              <Lightbulb size={16} aria-hidden className="mt-0.5 shrink-0 text-accent" />
              {text}
            </p>
          ) : null}
        </>
      )}
    </Panel>
  );
}

function BareTooltip({ active, payload, metric, model }: TooltipProps<number, string> & { metric: TrendMetric; model: OverviewModel }) {
  const row = payload?.[0]?.payload as { month: string; rev: number; pay: number; mau: number } | undefined;
  if (!active || !row) return null;
  const s = model.trend[metric];
  const i = s.months.findIndex((m) => m.month === row.month);
  const half = i < 6 ? s.h1 : s.h2;
  const vs = half && half > 0 ? row[metric] / half - 1 : null;
  const order = [metric, ...METRICS.map((m) => m.key).filter((k) => k !== metric)];
  return (
    <div className="w-[196px] rounded-control px-3 py-2" style={{ background: "var(--tip-bg)", color: "var(--tip-ink)", boxShadow: "var(--shadow-float)" }}>
      <p className="mb-1 text-micro opacity-80">{formatMonth(row.month, true)}</p>
      {order.map((k, j) => (
        <p key={k} className={`flex justify-between gap-2 ${j === 0 ? "text-section font-semibold" : "text-body"}`}>
          <span className="num">{k === "rev" ? formatBahtCompact(row.rev) : `${formatCount(row[k])} ราย`}</span>
          <span className="text-micro opacity-80">{label(k)}</span>
        </p>
      ))}
      {vs != null ? (
        <p className="mt-1 pt-1 text-micro opacity-80" style={{ borderTop: "1px solid color-mix(in srgb, var(--tip-ink) 25%, transparent)" }}>
          {label(metric)}{vs >= 0 ? "สูงกว่า" : "ต่ำกว่า"}ค่าเฉลี่ย{i < 6 ? "ครึ่งปีแรก" : "ครึ่งปีหลัง"} {formatPercent(Math.abs(vs))}
        </p>
      ) : null}
    </div>
  );
}
